library(tinytest)

new_package <- function(files, namespace = NULL, entry_point = "f") {
  dir <- tempfile("pkg")
  dir.create(file.path(dir, "inst", "tools"), recursive = TRUE)
  name <- basename(dir)
  writeLines(c(
    sprintf("Package: %s", name),
    "Version: 0.0.1",
    "Title: Test",
    "Imports: Rcpp",
    "LinkingTo: Rcpp, RcppThread"
  ), file.path(dir, "DESCRIPTION"))
  if (is.null(namespace)) {
    namespace <- c(
      sprintf("useDynLib(%s, .registration = TRUE)", name),
      "importFrom(Rcpp, evalCpp)",
      sprintf("export(%s)", entry_point)
    )
  }
  writeLines(namespace, file.path(dir, "NAMESPACE"))
  for (file in names(files)) {
    writeLines(files[[file]], file.path(dir, "inst", "tools", file))
  }
  dir
}

tools <- function(...) file.path("inst", "tools", c(...))

types_file <- c(
  "new_type(",
  "  Point,",
  "  slots(x |> type(double), y |> type(double))",
  ")"
)
entry_file <- c(
  "f <- function(p, i) {",
  "  argtypes(p |> type(Point), i |> type(int))",
  "  returntype(double)",
  "  s <- p$x + p$y",
  "  helper(s, i)",
  "}"
)
helpers_file <- c(
  "helper <- function(a, i) {",
  "  argtypes(a |> type(double), i |> type(int))",
  "  returntype(double)",
  "  v <- c(a, a)",
  "  v[[i]]",
  "}"
)
all_files <- list("types.R" = types_file, "entry.R" = entry_file, "helpers.R" = helpers_file)

# --- generated files ---------------------------------------------------------
dir <- new_package(all_files)
name <- basename(dir)
expect_equal(ast2ast::make_package(tools("types.R", "entry.R", "helpers.R"), "f", dir), name)

cpp <- readLines(file.path(dir, "src", "ast2ast_f.cpp"))
expect_true(grepl("Generated by ast2ast::make_package", cpp[[1]]))
expect_false(any(grepl("Rcpp::depends|Rcpp::plugins", cpp)))
expect_true(any(grepl("// [[Rcpp::export]]", cpp, fixed = TRUE)))
expect_true(any(grepl(sprintf("%s: helpers.R:5 (helper): return(v[[i]])", name), cpp, fixed = TRUE)))
expect_true(any(grepl(sprintf("%s: entry.R:5 (f): return(", name), cpp, fixed = TRUE)))

makevars <- readLines(file.path(dir, "src", "Makevars"))
expect_true(grepl("Generated by ast2ast::make_package", makevars[[1]]))
expect_true("CXX_STD = CXX20" %in% makevars)
expect_true(file.exists(file.path(dir, "src", "Makevars.win")))
expect_true(file.exists(file.path(dir, "inst", "include", "ast2ast", "etr.hpp")))
expect_true(any(grepl("^f <- function", readLines(file.path(dir, "R", "RcppExports.R")))))

# rerun: own generated files are overwritten without asking
expect_silent(ast2ast::make_package(tools("types.R", "entry.R", "helpers.R"), "f", dir))

# no types at all
dir_no_types <- new_package(list("entry.R" = c(
  "f <- function(a) {",
  "  argtypes(a |> type(double))",
  "  returntype(double)",
  "  a + 1",
  "}"
)))
expect_silent(ast2ast::make_package(tools("entry.R"), "f", dir_no_types))

# --- overwrite rule ----------------------------------------------------------
if (!interactive()) {
  dir <- new_package(all_files)
  dir.create(file.path(dir, "src"))
  writeLines("PKG_LIBS = -lfoo", file.path(dir, "src", "Makevars"))
  expect_error(
    ast2ast::make_package(tools("types.R", "entry.R", "helpers.R"), "f", dir),
    "was not generated by make_package"
  )
  expect_equal(readLines(file.path(dir, "src", "Makevars")), "PKG_LIBS = -lfoo")
  ast2ast::make_package(tools("types.R", "entry.R", "helpers.R"), "f", dir, overwrite = TRUE)
  expect_true(grepl("Generated by ast2ast::make_package", readLines(file.path(dir, "src", "Makevars"))[[1]]))
}

# --- paths and package setup ------------------------------------------------
expect_error(ast2ast::make_package("a.R", "f", tempdir()), "DESCRIPTION is missing")

dir <- new_package(all_files)
expect_error(ast2ast::make_package(tools("nope.R"), "f", dir), "do not exist")
writeLines(entry_file, file.path(dirname(dir), "outside.R"))
expect_error(ast2ast::make_package("../outside.R", "f", dir), "not inside")
dir.create(file.path(dir, "R"))
writeLines(entry_file, file.path(dir, "R", "entry.R"))
expect_error(ast2ast::make_package(file.path("R", "entry.R"), "f", dir), "Files in R/")

dir <- new_package(all_files, namespace = character())
expect_error(
  ast2ast::make_package(tools("types.R", "entry.R", "helpers.R"), "f", dir),
  "useDynLib.*importFrom.*export\\(f\\)"
)

# --- content of the files ----------------------------------------------------
dir <- new_package(list("entry.R" = c(entry_file, "x <- 1")))
expect_error(ast2ast::make_package(tools("entry.R"), "f", dir), "entry.R:7: x <- 1")

dir <- new_package(list("types.R" = types_file, "more.R" = types_file, "entry.R" = entry_file))
expect_error(ast2ast::make_package(tools("types.R", "more.R", "entry.R"), "f", dir), "more.R:1: Type Point is redefined")

dir <- new_package(list("entry.R" = entry_file, "again.R" = entry_file))
expect_error(ast2ast::make_package(tools("entry.R", "again.R"), "f", dir), "again.R:1: Function f is redefined")

dir <- new_package(all_files, entry_point = "g")
expect_error(ast2ast::make_package(tools("types.R", "entry.R", "helpers.R"), "g", dir), "Entry point g is not defined")

dir <- new_package(list("entry.R" = c("f <- function(a) {", "  argtypes(a |> type(double))", "  a", "}")))
expect_error(ast2ast::make_package(tools("entry.R"), "f", dir), "has to start with argtypes\\(...\\) and returntype\\(...\\)")

# --- install and call --------------------------------------------------------
if (!at_home()) exit_file("slow: installs a package; runs at home / CI only")

dir <- new_package(all_files)
name <- basename(dir)
ast2ast::make_package(tools("types.R", "entry.R", "helpers.R"), "f", dir)
lib <- tempfile("lib")
dir.create(lib)
status <- system2(file.path(R.home("bin"), "R"), c("CMD", "INSTALL", "-l", shQuote(lib), shQuote(dir)),
                  stdout = FALSE, stderr = FALSE)
expect_equal(status, 0L)
f <- getExportedValue(asNamespace(loadNamespace(name, lib.loc = lib)), "f")
p <- structure(list(x = 1, y = 2), class = "Point")
expect_equal(f(p, 1L), 3)
expect_false(exists("helper", envir = asNamespace(name), inherits = FALSE))
expect_error(f(p, 5L), sprintf("%s: helpers.R:5 (helper)", name), fixed = TRUE)
